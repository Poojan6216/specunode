"""Generate ``RESULTS.md`` from the committed results files. Never hand-edited.

Every figure in the output is read from ``bench/results/*.json``. If a file is missing, the
section says so rather than being quietly omitted -- an absent measurement and a measurement of
zero are different things, and a report that hides the first will eventually be read as the
second.

``python bench/report.py``
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "bench" / "results"

BANNER = """<!-- Generated by bench/report.py. Do not edit by hand: every number here is read
from a committed file in bench/results/, and editing this file would break the only link
between what is published and what was measured. Regenerate with `python bench/report.py`. -->
"""


def load(name: str) -> dict[str, Any] | None:
    path = RESULTS / name
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def ci(stat: dict[str, float]) -> str:
    return f"{stat['mean']:.4f} [{stat['ci95_low']:.4f}, {stat['ci95_high']:.4f}]"


def missing(section: str, command: str) -> str:
    return (
        f"### {section}\n\n"
        f"Not measured yet. Produce it with:\n\n```\n{command}\n```\n\n"
        "This section is present and empty on purpose: a measurement that has not been taken "
        "and a measurement of zero are different things.\n"
    )


def opportunity_section() -> str:
    report = load("opportunity.json")
    if report is None:
        return missing(
            "How much speculation a real corpus exposes",
            "python bench/corpus/fetch.py && python bench/offline/run_opportunity.py "
            "--out bench/results/opportunity.json",
        )
    corpus, o = report["corpus"], report["opportunity"]
    lines = [
        "### How much speculation a real corpus exposes",
        "",
        f"Corpus: `{corpus['dataset']}` ({corpus['source']}), "
        f"{o['trajectories']} trajectories, {o['steps']} tool calls. "
        f"Effect classes come from a committed hand-written table per tool name; anything "
        f"absent from it is a WRITE, exactly as in the runtime.",
        "",
        "Means with 95% percentile-bootstrap intervals over trajectories.",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Reads — speculable under any policy | {ci(o['read_fraction'])} |",
        f"| Calls that open a new model turn | {ci(o['calls_opening_a_new_model_turn'])} |",
        f"| Arguments referencing a prior result | {ci(o['args_referencing_a_prior_result'])} |",
        f"| PASTE speculable span (calls) | {ci(o['paste_speculable_span'])} |",
        "| Steps PASTE must skip that SpecuNode can stage | "
        f"{ci(o['steps_paste_must_skip_that_specunode_can_stage'])} |",
        f"| **SpecuNode span past a write (calls)** | {ci(o['specunode_post_write_span'])} |",
        "| Model turn consuming a write's result | "
        f"{ci(o['model_turn_consuming_a_write_result'])} |",
        "",
        f"Tier-1 **signature** predictability, leave-one-trajectory-out over "
        f"{o['signature_predictability']['sampled_trajectories']} trajectories "
        f"(not {o['trajectories']}; this measure is quadratic): "
        f"top-1 {o['signature_predictability']['top_1']:.4f}, "
        f"top-3 {o['signature_predictability']['top_3']:.4f}. "
        "A signature is the tool name plus its sorted argument *keys*. Argument **values** are "
        "not compared, while the runtime releases a write only on exact canonical equality of "
        "values -- so this is an upper bound on the acceptance rate, not the acceptance rate. "
        "It is published without an interval because it is a single leave-one-out pass.",
        "",
        "#### The anti-result, first",
        "",
        "**On this corpus, running ahead *past* a write buys nothing at all.** The span is "
        "0.0000, with a bootstrap interval that does not move off zero.",
        "",
        "The reason is structural rather than a limitation of the implementation: every tool "
        "call in these trajectories opens a new model turn. A staged write does not block the "
        "next tool call, but it does block the next model *turn*, because that turn would "
        "have to contain a placeholder where the real result belongs. When there is never a "
        "second call within a turn, there is nothing for the store buffer to run ahead into.",
        "",
        "That is the shape spec section 1 predicts gains nothing, and it is "
        f"{o['model_turn_consuming_a_write_result']['mean']:.1%} of this corpus.",
        "",
        "#### What the store buffer does unlock here",
        "",
        "A different quantity, and the one that is not zero. PASTE excludes a tool with side "
        "effects from speculation entirely, so it can speculate on "
        f"{o['read_fraction']['mean']:.1%} of steps. SpecuNode stages a write instead of "
        "refusing it, so a *predicted* write can be run ahead like any other call and "
        "discarded if the model decides otherwise — which covers the other "
        f"{o['steps_paste_must_skip_that_specunode_can_stage']['mean']:.1%}.",
        "",
        "That is an upper bound on opportunity, not a speedup. It is realisable only where the "
        f"predictor is right. The nearest measured proxy is signature top-1 at "
        f"{o['signature_predictability']['top_1']:.1%}, which is an upper bound on that and "
        "not a measurement of it. "
        "Neither number means anything alone, which is why they are printed together.",
        "",
    ]
    return "\n".join(lines)


def demo_section() -> str:
    report = load("demo_leak.json")
    if report is None:
        return missing(
            "Demo 1 — speculation without a store buffer", "python bench/demo.py --demo leak"
        )
    rows = [
        "### Demo 1 — speculation without a store buffer double-charges",
        "",
        f"{report['runs']} journaled transcripts through three runtimes, measuring "
        f"`{report['measured_tool']}`.",
        "",
        "| Runtime | Runs | Mispredictions | Charges reaching world "
        "| Charges from squashed branches |",
        "|---|---|---|---|---|",
    ]
    for arm in report["arms"]:
        rows.append(
            f"| {arm['runtime']} | {arm['runs']} | {arm['mispredictions']} | "
            f"{arm['effects_reaching_world']} | {arm['effects_from_squashed_branches']} |"
        )
    rows += ["", "The last column, and the fact that the second and third rows agree.", ""]
    return "\n".join(rows)


def attacks_section() -> str:
    report = load("attacks.json")
    if report is None:
        return missing("What beats it", "python bench/adversarial/run_attacks.py --all")
    rows = [
        "### What beats it",
        "",
        "Every strategy below defeats the runtime. Each reports a measured rate.",
        "",
        "| # | Strategy | Outcome | Measured |",
        "|---|---|---|---|",
    ]
    for attack in report["attacks"]:
        if attack["error"]:
            rows.append(
                f"| {attack['id']} | {attack['name']} | **error** | {attack['error'][:60]} |"
            )
            continue
        measured = ", ".join(f"{k}={v}" for k, v in attack["measured"].items())
        verdict = "beats it" if attack["defeated_runtime"] else "held"
        rows.append(f"| {attack['id']} | {attack['name']} | {verdict} | {measured} |")
    rows += ["", ""]
    return "\n".join(rows)


def invariants_section() -> str:
    chaos, concurrency = load("chaos.json"), load("concurrency.json")
    if chaos is None or concurrency is None:
        return missing(
            "Invariants under load",
            "python bench/chaos/run_chaos.py --out bench/results/chaos.json && "
            "python bench/chaos/run_chaos.py --concurrency --out bench/results/concurrency.json",
        )
    c, n = chaos["chaos"], concurrency["concurrency"]
    return "\n".join(
        [
            "### Invariants under load",
            "",
            "| Matrix | Runs | Leaks | Duplicate deliveries | Equivalence failures "
            "| Cross-branch observations |",
            "|---|---|---|---|---|---|",
            f"| Chaos (partition, duplicate, slow reads) | {c['runs']} | {c['leaks']} | "
            f"{c['duplicate_deliveries']} | {c['equivalence_failures']} | "
            f"{c['cross_branch_observations']} |",
            f"| Concurrency (shared journal, shared world) | {n['runs']} | {n['leaks']} | "
            f"{n['duplicate_deliveries']} | {n['equivalence_failures']} | "
            f"{n['cross_branch_observations']} |",
            "",
            f"The chaos matrix produced {c['dead_letters']} dead letters, which is the "
            "partition rounds behaving correctly: a non-idempotent effect in an ambiguous "
            "window is dead-lettered rather than guessed at.",
            "",
        ]
    )


def overhead_section() -> str:
    report = load("overhead.json")
    if report is None:
        return missing(
            "What the runtime costs",
            "python bench/offline/run_opportunity.py --overhead --out bench/results/overhead.json",
        )
    o = report["overhead"]
    return "\n".join(
        [
            "### What the runtime costs",
            "",
            f"The same LangGraph app, the same scripted model, the same fake world, run "
            f"{o['rounds']} times each way: once bare, once through the runtime. The difference "
            "is the journal's fsyncs, effect classification, staging and the ledger.",
            "",
            "| | ms per run |",
            "|---|---|",
            f"| Bare graph | {o['bare_ms']['mean']} |",
            f"| Under the runtime | {o['wrapped_ms']['mean']} |",
            f"| **Overhead** | **{o['overhead_ms_per_run']}** "
            f"({o['overhead_ms_per_step']} per step) |",
            "",
            f"That is {o['overhead_fraction_of_wall_clock']:.1%} of wall clock here, and the "
            "percentage is the misleading half of it. " + str(o["note"]),
            "",
        ]
    )


def latency_section() -> str:
    return (load("latency.json") and "") or missing(
        "Wall-clock latency",
        "ANTHROPIC_API_KEY=... python bench/online/run_latency.py --out bench/results/latency.json",
    )


def build() -> str:
    return "\n".join(
        [
            BANNER,
            "# RESULTS",
            "",
            "Every figure here is read from a committed file in `bench/results/`, produced by "
            "the command named beside it. The negative results come first, because they are "
            "the ones a reader is least likely to go looking for.",
            "",
            "---",
            "",
            opportunity_section(),
            "---",
            "",
            attacks_section(),
            "---",
            "",
            demo_section(),
            "---",
            "",
            invariants_section(),
            "---",
            "",
            overhead_section(),
            "---",
            "",
            latency_section(),
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate RESULTS.md")
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args(argv)

    target = REPO / "RESULTS.md"
    body = build()
    if args.check:
        current = target.read_text(encoding="utf-8") if target.is_file() else ""
        if current != body:
            print("RESULTS.md is out of date; run python bench/report.py", file=sys.stderr)
            return 1
        return 0
    target.write_text(body, encoding="utf-8")
    print(f"wrote {target} ({len(body.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
