def _band(ci: dict[str, float] | None) -> str:
    if not ci:
        return "not measured"
    return f"{ci['mean']:+.1%} [{ci['ci95_low']:+.1%}, {ci['ci95_high']:+.1%}]"


def latency_section() -> str:
    report = load("latency.json")
    if report is None:
        return missing(
            "Wall-clock latency",
            "ANTHROPIC_API_KEY=... python bench/online/run_latency.py "
            "--out bench/results/latency.json",
        )
    if not report.get("is_real_model"):
        return (
            "### Wall-clock latency\n\n"
            "The harness has run, against its deterministic stand-in rather than a model, so "
            "there is still no wall-clock measurement here. Run it with an API key for figures "
            "anyone should quote.\n"
        )
    arms = {arm for entry in report["workloads"].values() for arm in entry["arms"]}
    if "B_strict_seq" not in arms:
        leaks = sum(
            int(s["leaks"]) for e in report["workloads"].values() for s in e["arms"].values()
        )
        return (
            "### Wall-clock latency, against a real model\n\n"
            f"The {report['tasks_completed']} runs in `bench/results/latency.json` were taken "
            "before two faults in their arms were found: their `B_seq` already issued reads "
            "early, so it was not the sequential baseline it was labelled as, and their "
            "`B_readonly_spec` was given no predictor, so it never guessed. Their savings are "
            "measured against the wrong baseline and are not quoted here. The 0 ms rung of the "
            "sweep below measures the same thing with the corrected arms; re-running this table "
            "is pending.\n\n"
            f"**Effects reaching the world from a branch that never retired: {leaks}.** That "
            "count does not depend on which arm was the baseline.\n"
        )
    lines = [
        "### Wall-clock latency, against a real model",
        "",
        f"Target: `{report['target_model']}`. {report['tasks_completed']} runs, "
        f"{report['tasks_requested']} per arm per sample app, with tools exactly as fast as the "
        "in-memory sample world makes them. Means with 95% bootstrap intervals on the "
        f"*difference*. Spend: ${report['estimated_spend_usd']}, at the per-model prices "
        "printed in the results file.",
        "",
        "Four arms, and the first is the one every earlier version of this table was missing. "
        "**B_strict_seq** waits for each model turn to end and then calls its tools in order. "
        "**B_seq** adds tier-0 early issue -- a read starts the moment its block parses -- and "
        "nothing else. **B_readonly_spec** adds guessing, but a guessed write is a barrier: "
        "PASTE's rule, credited. **B_specunode** guesses writes too and stages them in the "
        "store buffer, which is what this project adds.",
        "",
        "| Workload | Early issue only | + guessing reads | + guessing writes too | Leaks |",
        "|---|---|---|---|---|",
    ]
    total_leaks = 0
    for name, entry in sorted(report["workloads"].items()):
        strict = entry.get("saving_vs_strict_seq_ci95") or {}
        leaks = sum(int(s["leaks"]) for s in entry["arms"].values())
        total_leaks += leaks
        lines.append(
            f"| `{name}` | {_band(strict.get('B_seq'))} | "
            f"{_band(strict.get('B_readonly_spec'))} | {_band(strict.get('B_specunode'))} | "
            f"{leaks} |"
        )
    lines += [
        "",
        "Each cell is the wall clock saved against `B_strict_seq`; a **negative** saving means "
        "that arm was slower. An interval that spans zero resolves no difference.",
        "",
        f"**Effects reaching the world from a branch that never retired: {total_leaks}.** That "
        "is the number this project exists to keep at zero, and it is the only one here that "
        "is a claim about correctness rather than about speed.",
        "",
    ]
    return "\n".join(lines)


def break_even_section() -> str:
    report = load("break_even.json")
    if report is None:
        return missing(
            "What a guess is worth",
            "python bench/offline/run_break_even.py --out bench/results/break_even.json",
        )
    lines = [
        "### What a guess is worth",
        "",
        "The acceptance rates above say how often a predictor is right. This says what being "
        "right is *worth*, which no real predictor can answer on its own: a guesser that knows "
        "the model's turn in advance and names the right next call with a chosen probability, "
        "otherwise a valid wrong one, measured against tier-0 early issue alone -- so each cell "
        "is what guessing adds *on top of* what the runtime already does. No model and no "
        f"network: the stand-in streams {report['think_ms_per_block']:.0f} ms per block, "
        f"calibrated from the real sweep, {report['tasks_per_point']} runs per cell, on "
        f"`{report['workload']}`, the one sample app that hands its turn to the runtime.",
        "",
        "| Tool latency | Accuracy | Guess reads and writes | Guess reads only |",
        "|---|---|---|---|",
    ]
    for ms, point in sorted(report["points"].items(), key=lambda kv: int(kv[0])):
        for alpha, arms in point["by_alpha"].items():
            lines.append(
                f"| {ms} ms | {alpha} | "
                f"{_band(arms['reads_and_writes']['saving_vs_early_issue_ci95'])} | "
                f"{_band(arms['reads_only']['saving_vs_early_issue_ci95'])} |"
            )
    lines += [
        "",
        "Three things this settles, each of which the scheduler's structure predicts and none of "
        "which was a result until it was measured:",
        "",
        "- **A hit is worth at most one block of streaming.** The drafter is asked after each "
        "block and the next block resolves the guess, so a correct guess starts its call one "
        "block early -- which is worth something only when the call is slower than early issue "
        "could already hide.",
        "- **A miss costs no wall clock.** It is squashed when the real block arrives and the "
        "real call is issued as it always was. What a miss costs is money: the upstream read it "
        "made, and for a draft model the tokens.",
        "- **Guessing a write adds nothing over guessing reads only.** A staged write cannot be "
        "dispatched before its branch retires, and the drafter does not chain past one. The "
        "store buffer is what makes guessing a write *safe*; it does not make it *faster*.",
        "",
    ]
    return "\n".join(lines)


def model_bound_section() -> str:
    report = load("model_bound.json")
    title = "When the model is the slow part: fewer replies, and replies side by side"
    if report is None:
        return missing(
            title, "python bench/offline/run_model_bound.py --out bench/results/model_bound.json"
        )
    stand_in = report["stand_in"]
    totals = report["totals"]
    lines = [
        f"### {title}",
        "",
        "A guess buys at most one block of a model's stream (above). When the model is what a "
        "run waits on, the time is in the replies themselves, and infrastructure has two levers "
        "left: how many replies a run needs, and how many of them it waits on at once. Both "
        "are measured here against a stand-in model whose reply takes "
        f"{stand_in['reply_ms']:.0f} ms before its first block -- reading the prompt and "
        f"thinking -- and {stand_in['block_ms']:.0f} ms per block. Those are settings, not "
        "measurements: the wall clock below is what the runtime makes of them. The reply "
        f"counts and in-flight counts do not depend on them. {report['runs_per_cell']} runs "
        "per cell, with a bootstrap interval on the difference.",
        "",
        "**Multi-call replies** (`examples/incident_agent`). One alert -- four pipelines to "
        "check, a runbook to read, two restarts, one summary -- worked one call per reply, "
        "which is how every turn in the corpus above behaves, and with every independent call "
        "in one reply. The runtime runs a reply's reads together as they parse, holds its "
        "writes until the reply is durable, and hands every result back in one message.",
        "",
        "| Tool latency | One call per reply | Every independent call at once | Saving |",
        "|---|---|---|---|",
    ]
    for ms, point in sorted(report["replies"].items(), key=lambda kv: int(kv[0])):
        one, many = point["one_call"], point["parallel"]
        lines.append(
            f"| {ms} ms | {one['replies']} replies, {one['wall_ms_mean']:.0f} ms | "
            f"{many['replies']} replies, {many['wall_ms_mean']:.0f} ms | "
            f"{_band(point['saving_ci95'])} |"
        )
    lines += [
        "",
        "**Parallel nodes** (`examples/fanout_agent`). Three independent checks, each one model "
        "reply, then a report. The router names the three at once; the runtime runs their "
        "bodies side by side and retires them in the order it named them, so their effects "
        "reach the world in that order however the bodies interleaved.",
        "",
        "| Tool latency | One after another | Side by side | Saving |",
        "|---|---|---|---|",
    ]
    for ms, point in sorted(report["branches"].items(), key=lambda kv: int(kv[0])):
        serial, side = point["one_at_a_time"], point["side_by_side"]
        lines.append(
            f"| {ms} ms | {serial['in_flight_max']} model call in flight, "
            f"{serial['wall_ms_mean']:.0f} ms | {side['in_flight_max']} in flight, "
            f"{side['wall_ms_mean']:.0f} ms | {_band(point['saving_ci95'])} |"
        )
    by_hand = [
        (ms, point) for ms, point in report["replies"].items() if point.get("vs_by_hand_ci95")
    ]
    if by_hand:
        lines += [
            "",
            "**What the safety costs.** Against the fastest loop a developer would write by "
            "hand -- stream the reply, then run every call it asked for at once, with no journal, "
            "no store buffer, no order among the writes and nothing a crash could be resumed from "
            "-- on the same replies, the same tools and the same stand-in. The interval is on the "
            "difference, where a negative figure is the runtime being slower.",
            "",
            "| Tool latency | Workload | By hand | Through the runtime | Runtime slower by "
            "| Interval on the difference |",
            "|---|---|---|---|---|---|",
        ]
        for ms, point in sorted(by_hand, key=lambda kv: int(kv[0])):
            fan = report["branches"][ms]
            lines += [
                f"| {ms} ms | alert, several calls per reply | "
                f"{point['by_hand']['wall_ms_mean']:.0f} ms | "
                f"{point['parallel']['wall_ms_mean']:.0f} ms | "
                f"{point['cost_vs_by_hand']:.1%} | {_band(point['vs_by_hand_ci95'])} |",
                f"| {ms} ms | three checks side by side | "
                f"{fan['by_hand']['wall_ms_mean']:.0f} ms | "
                f"{fan['side_by_side']['wall_ms_mean']:.0f} ms | "
                f"{fan['cost_vs_by_hand']:.1%} | {_band(fan['vs_by_hand_ci95'])} |",
            ]
        lines += [
            "",
            "Where it goes: the journal's writes, which are what a resume and a replay are made "
            "of; "
            "one round of re-checking each witnessed read before the writes it informed are "
            "released, made concurrently for every lane of a group; and a reply's writes sent one "
            "after another in the order the model listed them, which the loop by hand sends at "
            "once. What it buys is everything in the next sections.",
        ]
    lines += [
        "",
        f"Runs that changed the world exactly as a correct run does: {totals['correct']} of "
        f"{totals['runs']}. **Effects reaching the world from a branch that never retired: "
        f"{totals['leaks']}.**",
        "",
        _real_model_pointer(),
        "",
    ]
    return "\n".join(lines)


def _real_model_pointer() -> str:
    """Where the stand-in's open question is answered -- or that it has not been."""
    online = load("model_bound_online.json")
    if online is not None and online.get("is_real_model"):
        return (
            "What a real model does with the same two changes, and what prompt caching saves, "
            "is the next section."
        )
    return (
        "What this does not show is what a real model does when told it may ask for several "
        "calls at once, or what prompt caching takes off each reply. Both need a real model, "
        "and neither is measured yet."
    )


#: The incident-agent cells of ``model_bound_online.json``, in the order a reader compares them.
_ONLINE_REPLY_CELLS = (
    ("one_call/no_cache", "One call per reply, no cache -- **before**"),
    ("one_call/cache", "One call per reply, cached"),
    ("parallel/no_cache", "Several calls per reply, no cache"),
    ("parallel/cache", "Several calls per reply, cached -- **after**"),
    ("default/cache", "No guidance either way, cached"),
)
_ONLINE_COMPARISONS = (
    ("caching", "Prompt caching alone (one call per reply)"),
    ("multi_call_replies", "Several calls per reply (both cached)"),
    ("before_to_after", "**Before to after: both levers**"),
    ("parallel_nodes", "Parallel nodes (three checks, then a report)"),
)


def model_bound_online_section() -> str:
    report = load("model_bound_online.json")
    title = "Fewer replies, caching and parallel nodes, against a real model"
    if report is None:
        return missing(
            title,
            "ANTHROPIC_API_KEY=... python bench/online/run_model_bound.py "
            "--out bench/results/model_bound_online.json",
        )
    if not report.get("is_real_model"):
        return (
            f"### {title}\n\nThe harness has run against its stand-in rather than a model. Run "
            "it with an API key for figures anyone should quote.\n"
        )
    cells = report["cells"]
    lines = [
        f"### {title}",
        "",
        f"Target: `{report['target_model']}`. The same seven configurations as above, run "
        f"round-robin -- one run of each per round, {report['runs_requested']} rounds -- so "
        "drift in the API's latency lands on all of them alike. Spend: "
        f"${report['estimated_spend_usd']} of a ${report['budget_usd_cap']} cap.",
        "",
        "**One call per reply is enforced, not asked for.** In a first attempt at this run, "
        "the model told in its system prompt to make one call per reply batched its calls "
        "anyway, exactly as it did with no guidance, so the attempt was stopped in its second "
        "round. This arm now also sets the API's `disable_parallel_tool_use`, which is what an "
        "app that runs one call per reply effectively has. Cached runs of one configuration "
        "follow each other well inside the cache's five-minute lifetime, so from the second "
        "round on they start with the system prompt already cached: the steady state of an "
        "agent that works more than one alert.",
        "",
        "| Configuration | Replies | Calls per reply | Wall clock | Cost per run | Correct |",
        "|---|---|---|---|---|---|",
    ]
    for key, label in _ONLINE_REPLY_CELLS:
        cell = cells.get(key) or {}
        if not cell.get("n"):
            lines.append(f"| {label} | not measured | | | | |")
            continue
        lines.append(
            f"| {label} | {cell['replies_mean']:.1f} | {cell['calls_per_reply']:.2f} | "
            f"{cell['wall_ms_mean']:.0f} ms | ${cell['usd_per_run']:.4f} | "
            f"{cell['correct']} of {cell['n']} |"
        )
    lines += [
        "",
        "| Change | Wall clock saved | Cost saved |",
        "|---|---|---|",
    ]
    for key, label in _ONLINE_COMPARISONS:
        comparison = report["comparisons"].get(key) or {}
        cost = _band(comparison.get("cost_saving_ci95")) if key != "parallel_nodes" else "--"
        lines.append(f"| {label} | {_band(comparison.get('wall_saving_ci95'))} | {cost} |")
    before, after = cells.get("one_call/no_cache") or {}, cells.get("parallel/cache") or {}
    habit = cells.get("default/cache") or {}
    comparisons = report["comparisons"]
    caching = (comparisons.get("caching") or {}).get("cost_saving_ci95") or {}
    if before.get("n") and after.get("n") and habit.get("n") and caching:
        lines += [
            "",
            "Three things this says, in the order they matter:",
            "",
            f"- **The model already asks for independent calls together.** Told nothing either "
            f"way, it used {habit['replies_mean']:.1f} replies, the same as with guidance. "
            "What kept a run at one call per reply was the app around the model running only "
            "one -- which is what this arm's API switch reproduces.",
            f"- **Fewer replies save each reply's fixed cost, not the writing.** "
            f"{before['replies_mean']:.1f} replies became {after['replies_mean']:.1f}, and the "
            "time saved is smaller than that, because a reply that asks for several calls takes "
            "longer to write than one that asks for one.",
            f"- **Caching cut the bill by {caching['mean']:.1%} and did not change the wall "
            "clock** at a prompt this short: reading a prompt of a few thousand tokens is a small "
            "part of a reply's time, and the interval on the time saved spans zero. On a long "
            "prompt, where reading it is a larger part of each reply, it should save time too; "
            "that is not measured here.",
        ]
    serial, side = cells.get("nodes/one_at_a_time") or {}, cells.get("nodes/side_by_side") or {}
    leaks = sum(int(cell.get("leaks", 0)) for cell in cells.values())
    # Per configuration, because the totals are not in the results file and a sum computed
    # here would be a number nobody measured (Hard Rule 12).
    measured = [cell for cell in cells.values() if cell.get("n")]
    sizes = {int(cell["n"]) for cell in measured}
    if measured and all(cell["correct"] == cell["n"] for cell in measured) and len(sizes) == 1:
        (size,) = sizes
        verdict = (
            "Every run of every configuration changed the world exactly as a correct run does, "
            f"{size} of {size} in each."
        )
    else:
        verdict = "Runs that changed the world exactly as a correct run does: " + ", ".join(
            f"{name} {cell['correct']} of {cell['n']}" for name, cell in cells.items()
        )
    lines += [
        "",
        "Parallel nodes, with each check one real model reply: "
        f"{serial.get('wall_ms_mean', 0):.0f} ms one after another, "
        f"{side.get('wall_ms_mean', 0):.0f} ms side by side.",
        "",
        f"{verdict} **Effects reaching the world from a branch that never retired: {leaks}.**",
        "",
    ]
    if report.get("halted_at"):
        lines += [f"Halted at the spend cap: {report['halted_at']}.", ""]
    if report.get("failure"):
        lines += [f"Stopped on a failed run: {report['failure']}.", ""]
    return "\n".join(lines)


_CRASH_SYSTEMS = (
    ("plain_loop", "A plain async loop"),
    ("langgraph_nodes", "LangGraph, a checkpointed node per customer"),
    ("langgraph_tasks", "LangGraph, each call a `@task` -- its recommended pattern"),
    ("specunode", "SpecuNode"),
    ("specunode_reconcile", "SpecuNode, each tool with a `reconcile`"),
)


def crash_safety_section() -> str:
    report = load("crash_safety.json")
    title = "Pull the plug: what a crash sends twice"
    if report is None:
        return missing(
            title, "python bench/offline/run_crash_safety.py --out bench/results/crash_safety.json"
        )
    systems = report["systems"]
    crashes = report["crash_points"]
    writes = report["writes"]
    lines = [
        f"### {title}",
        "",
        "The same billing run, five ways: look up three customers, charge each one, send each a "
        f"receipt, post one summary -- {writes} effects on the world, none of which may happen "
        "twice. The process is killed at each of them, once just before the request reaches the "
        "upstream (*request lost*) and once just after the upstream took effect but before the "
        "reply came back (*reply lost*), and restarted the way each system restarts: "
        f"{crashes} crashes each. No model and no network; the systems run identical business "
        f"logic against the same upstream. LangGraph {report['langgraph']}.",
        "",
        "| System | Finished, every effect once | Stopped for a human, nothing twice "
        "| Sent something twice | Extra effects in the world |",
        "|---|---|---|---|---|",
    ]
    for key, label in _CRASH_SYSTEMS:
        row = systems.get(key)
        if row is None:
            continue
        lines.append(
            f"| {label} | {row['exact']} | {row['held']} | {row['duplicated']} | "
            f"{row['duplicate_effects']} |"
        )
    tasks, ours = systems.get("langgraph_tasks") or {}, systems.get("specunode") or {}
    reconciled = systems.get("specunode_reconcile") or {}
    if tasks and ours and reconciled:
        lines += [
            "",
            "What it says:",
            "",
            "- **A lost reply is the crash that double-charges, and checkpointing does not close "
            "it.** LangGraph's recommended pattern re-runs a task whose reply it never saw, so "
            f"{tasks['duplicated']} of its {crashes} crashes sent an effect twice -- every one "
            "where the reply was lost -- and it finished cleanly on every one where the request "
            "was. An expert can close that window by deriving a stable key per task and passing "
            "it to an upstream that honours one; that is the work the runtime here does for "
            "every effect.",
            "- **SpecuNode sent nothing twice in any of them.** Every effect is claimed in the "
            "journal under a deterministic key before it is sent, so a restart knows which "
            "effects may already be out. It cannot tell a request that never arrived from one "
            "whose reply was lost, so without more to go on it stops and asks a human -- in "
            f"{ours['held']} of {crashes}, including the ones where sending again would have "
            "been safe.",
            "- **Given a way to ask, it finished every one, with nothing sent twice and "
            "nothing missing.** A tool's `reconcile` "
            "answers *did the request under this key take effect?* from the upstream's own "
            "record of the key -- a payment's idempotency key, a unique request id. With it, "
            f"{reconciled['exact']} of {crashes} crashes finished with every effect in the "
            "world once and every receipt naming its customer's real charge.",
            "",
        ]
    return "\n".join(lines)


