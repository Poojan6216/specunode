"""Effect classes for the corpus, written by hand, per tool name.

Spec task 6.1 is explicit that these are **never** assigned by a heuristic on the tool's name or
arguments, and that a tool not in this table is a `WRITE` in the analysis exactly as it would be
in the runtime. That rule is the whole reason the opportunity numbers mean anything: a table
generated by guessing which tools look safe would make the analysis measure the guess.

The corpus is OpenHands trajectories, so the vocabulary is a coding agent's.

Two judgements worth stating, because they shape the result:

``str_replace_editor`` is a **WRITE**, although its ``view`` command is a read. The table is per
tool *name*, and this tool can create files and replace text. Classifying it by inspecting the
``command`` argument would be exactly the argument-level heuristic the rule forbids, and the
runtime could not do it either without the developer declaring it.

``think`` is a **READ**. It records a thought and touches nothing outside the trajectory. It is
the only tool here that is safe to speculate on under any policy, which is itself part of the
finding.
"""

from __future__ import annotations

from typing import Final, Literal

EffectLabel = Literal["read", "write"]

#: Hand-written, one entry per tool name. Anything absent is a WRITE.
CORPUS_EFFECT_CLASSES: Final[dict[str, EffectLabel]] = {
    "think": "read",
    # A scratchpad tool some traces use instead of `think`.
    "note": "read",
}

#: Tools seen in the corpus that were considered and deliberately left as WRITE, so a later
#: reader can tell "not yet classified" from "classified as a write".
CONSIDERED_AND_LEFT_AS_WRITE: Final[tuple[str, ...]] = (
    "str_replace_editor",  # can create and replace file contents
    "execute_bash",  # arbitrary shell
    "execute_ipython_cell",  # arbitrary code
    "browser",  # navigation can trigger effects upstream
    "finish",  # signals completion; treated as an effect on the run
    "web_read",  # fetches a URL, which can be metered or logged upstream
    # Seen in the corpus. Probably a planning scratchpad like `think`, but "probably" is the
    # inference this table exists to avoid, so it stays a WRITE until someone checks.
    "task_tracker",
)


def effect_of(tool: str) -> EffectLabel:
    """The declared class, or ``write`` for anything nobody classified."""
    return CORPUS_EFFECT_CLASSES.get(tool, "write")
